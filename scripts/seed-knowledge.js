// ========== 主函数 ==========
async function main() {
  const args = process.argv.slice(2)

  // JSON 导出模式（不需要数据库连接）
  if (args.includes('--export-json') || args.includes('--json')) {
    const fs = require('fs')
    const path = require('path')

    // JSON Lines 格式（CloudBase 控制台导入用，每行一个文档，后缀 .json）
    const jsonlPath = path.join(__dirname, 'knowledge_seeds.json')
    const jsonlLines = SEED_SPOTS.map(s => JSON.stringify(s)).join('\n')
    fs.writeFileSync(jsonlPath, jsonlLines, 'utf-8')

    console.log(`✅ 种子数据已导出: ${jsonlPath}`)
    console.log(`   格式: JSON Lines（每行一个 JSON 对象）`)
    console.log(`   共 ${SEED_SPOTS.length} 个景点`)
    console.log('')
    console.log('📝 下一步:')
    console.log('   1. 打开 CloudBase 控制台 → 数据库 → knowledge 集合')
    console.log('   2. 点击「导入」按钮')
    console.log('   3. 选择 knowledge_seeds.json')
    console.log('   4. 控制台会自动识别为 JSON Lines 格式并导入')
    process.exit(0)
  }

  // 尝试加载 CloudBase Node SDK
  let cloudbase
  try {
    cloudbase = require('@cloudbase/node-sdk')
  } catch (e) {
    console.error('❌ 请先安装 @cloudbase/node-sdk:')
    console.error('   npm install @cloudbase/node-sdk')
    console.error('')
    console.error('💡 或者导出 JSON 文件手动导入（无需 SDK 和密钥）:')
    console.error('   node scripts/seed-knowledge.js --export-json')
    process.exit(1)
  }

  // 优先从命令行参数读取，其次从环境变量读取
  let secretId = ''
  let secretKey = ''

  // 支持: node seed-knowledge.js SECRET_ID SECRET_KEY
  // 注意跳过 --xxx 标记
  const posArgs = args.filter(a => !a.startsWith('--'))
  if (posArgs.length >= 2) {
    secretId = posArgs[0]
    secretKey = posArgs[1]
  } else {
    secretId = process.env.CLOUDBASE_SECRET_ID || ''
    secretKey = process.env.CLOUDBASE_SECRET_KEY || ''
  }

  if (!secretId || !secretKey) {
    console.error('❌ 请提供 CloudBase 管理员凭证，或使用 --export-json 导出模式')
    console.error('')
    console.error('   方式一（导出 JSON → 控制台手动导入，推荐）:')
    console.error('     node scripts/seed-knowledge.js --export-json')
    console.error('')
    console.error('   方式二（命令行参数，直接写入）:')
    console.error('     node scripts/seed-knowledge.js 你的SecretId 你的SecretKey')
    console.error('')
    console.error('   方式三（环境变量）:')
    console.error('     PowerShell: \$env:CLOUDBASE_SECRET_ID=\"xxx\"; \$env:CLOUDBASE_SECRET_KEY=\"xxx\"')
    console.error('     CMD:        set CLOUDBASE_SECRET_ID=xxx && set CLOUDBASE_SECRET_KEY=xxx')
    console.error('     Git Bash:   export CLOUDBASE_SECRET_ID=xxx CLOUDBASE_SECRET_KEY=xxx')
    process.exit(1)
  }

  console.log('🔧 正在初始化 CloudBase...')
  const app = cloudbase.init({
    env: ENV_ID,
    secretId,
    secretKey
  })

  const db = app.database()
  const coll = db.collection('knowledge')

  console.log(`📦 准备导入 ${SEED_SPOTS.length} 个景点到 knowledge 集合...\n`)

  let success = 0
  let skipped = 0
  let failed = 0

  for (const [idx, spot] of SEED_SPOTS.entries()) {
    try {
      // 检查是否已存在同名+同 areaId 的景点
      const { data: existing } = await coll
        .where({ name: spot.name, areaId: spot.areaId, type: 'spot' })
        .limit(1)
        .get()

      if (existing && existing.length > 0) {
        console.log(`⏭  跳过 #${idx + 1} ${spot.name}（已存在）`)
        skipped++
        continue
      }

      // 写入新文档
      await coll.add({
        ...spot,
        createTime: new Date(),
        updateTime: new Date()
      })

      console.log(`✅ #${idx + 1} ${spot.name}（${spot.docId}）导入成功`)
      success++
    } catch (err) {
      console.error(`❌ #${idx + 1} ${spot.name} 导入失败:`, err.message)
      failed++
    }
  }

  console.log(`\n📊 导入完成: 成功 ${success}, 跳过(已存在) ${skipped}, 失败 ${failed}`)

  if (failed > 0) {
    console.log('\n⚠️  部分数据导入失败，请检查 CloudBase 权限配置。')
    process.exit(1)
  }

  console.log('🎉 种子数据导入全部完成！')
  process.exit(0)
}

main()
